chrome.commands.onCommand.addListener(async (command, tab) => {
  if (command === 'toggle-notes' || command === 'highlight-selection') {
    if (!tab) [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (tab) notesCommand(tab, command === 'toggle-notes' ? { type: 'kn-toggle' } : { type: 'kn-highlight', color: 'yellow' });
    return;
  }
  if (command === 'record-screen') {
    if (!tab) [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (tab) openRecord(tab);
    return;
  }
  if (command === 'screenshot-region' || command === 'investigate') {
    if (!tab) [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (tab) { if (command === 'investigate') openInvestigate(tab, { view: 'entities' }); else startShot(tab, 'region'); }
    return;
  }
  if (command === 'save-page' || command === 'save-video') {
    if (!tab) [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (tab) openSave(tab, { view: command === 'save-video' ? 'video' : 'document' });
    return;
  }
  if (command !== 'toggle-pause') return;
  const s = await getState();
  if (s.tabId != null) toTab(s.tabId, { type: 'kr-toggle-pause' });
});

// ---------- Notes ----------

async function ensureNotes(tabId) {
  const pong = await toTab(tabId, { type: 'kn-ping' });
  if (pong && pong.alive) return true;
  try {
    await chrome.scripting.insertCSS({ target: { tabId }, files: ['notes.css'] });
    await chrome.scripting.executeScript({ target: { tabId }, files: ['notes-core.js', 'notes-dom.js', 'notes.js'] });
    return true;
  } catch (e) {
    console.warn('PageMate notes cannot run on this page:', e.message);
    return false;
  }
}

async function notesCommand(tab, msg) {
  if (!tab || tab.id == null) return;
  if (!(await ensureNotes(tab.id))) {
    flashBadge(tab.id, '!', 'Notes can’t run on this page (browser-internal or protected page)');
    return;
  }
  clearBadge(tab.id);
  // The script has just been injected: give it a moment to finish loading its notes.
  for (let i = 0; i < 10; i++) {
    const r = await toTab(tab.id, msg);
    if (r) return;
    await new Promise(res => setTimeout(res, 120));
  }
}

async function openNotesManager(focusKey) {
  const url = chrome.runtime.getURL('notes.html') + (focusKey ? '#focus=' + encodeURIComponent(focusKey) : '');
  const stored = await chrome.storage.session.get('krNotesTab').catch(() => ({}));
  const id = stored.krNotesTab;
  if (id != null) {
    try {
      const t = await chrome.tabs.get(id);
      await chrome.tabs.update(t.id, { active: true, url });
      if (t.windowId != null) chrome.windows.update(t.windowId, { focused: true }).catch(() => {});
      return;
    } catch (_) {}
  }
  const t = await chrome.tabs.create({ url });
  await chrome.storage.session.set({ krNotesTab: t.id }).catch(() => {});
}

// Once access to sites is allowed, pages that already have notes get their highlights back
// automatically. The registered script only looks up "do I have notes for this page?".
async function syncNotesBoot() {
  try {
    const has = await chrome.permissions.contains({ origins: KR_ALL_SITES });
    const { notesAuto } = await chrome.storage.sync.get({ notesAuto: true });
    const registered = await chrome.scripting.getRegisteredContentScripts({ ids: ['kn-boot'] });
    if (has && notesAuto) {
      if (!registered.length) {
        await chrome.scripting.registerContentScripts([{ id: 'kn-boot', matches: KR_ALL_SITES, js: ['notes-core.js', 'notes-boot.js'], runAt: 'document_idle', persistAcrossSessions: true }]);
      }
    } else if (registered.length) {
      await chrome.scripting.unregisterContentScripts({ ids: ['kn-boot'] });
    }
  } catch (e) {
    console.warn('PageMate notes boot:', e.message);
  }
}
syncNotesBoot();
