chrome.permissions.onRemoved.addListener(syncNotesBoot);
chrome.storage.onChanged.addListener((changes, area) => { if (area === 'sync' && changes.notesAuto) syncNotesBoot(); });

// ---------- the Save page ----------

// Which Save tab belongs to which page. (We can't search tabs by URL: without the
// "tabs" permission the browser hides every tab's address, even our own pages'.)
const SAVE_TABS_KEY = 'krSaveTabs';

async function openSave(tab, { view = 'document', scope, frameId, srcUrl } = {}) {
  if (!tab || tab.id == null) return;
  const q = new URLSearchParams({ tab: String(tab.id), view });
  if (scope) q.set('scope', scope);
  if (frameId != null && frameId > 0) q.set('frame', String(frameId));
  if (srcUrl) q.set('src', srcUrl);
  const url = chrome.runtime.getURL('save.html?' + q);

  const stored = await chrome.storage.session.get(SAVE_TABS_KEY).catch(() => ({}));
  const map = stored[SAVE_TABS_KEY] || {};
  // Reuse the Save tab already open for this page, if any.
  if (map[tab.id] != null) {
    try {
      const existing = await chrome.tabs.get(map[tab.id]);
      await chrome.tabs.update(existing.id, { url, active: true });
      if (existing.windowId != null) chrome.windows.update(existing.windowId, { focused: true }).catch(() => {});
      return;
    } catch (_) { delete map[tab.id]; } // it was closed
  }
  const created = await chrome.tabs.create({ url, index: tab.index + 1, openerTabId: tab.id, active: true });
  map[tab.id] = created.id;
  await chrome.storage.session.set({ [SAVE_TABS_KEY]: map }).catch(() => {});
}

chrome.tabs.onRemoved.addListener(async tabId => {
  const nt = await chrome.storage.session.get('krNotesTab').catch(() => ({}));
  if (nt.krNotesTab === tabId) chrome.storage.session.remove('krNotesTab').catch(() => {});
  const stored = await chrome.storage.session.get(SAVE_TABS_KEY).catch(() => ({}));
  const map = stored[SAVE_TABS_KEY];
  if (!map) return;
  let changed = false;
  for (const [src, save] of Object.entries(map)) {
    if (Number(src) === tabId || save === tabId) { delete map[src]; changed = true; }
  }
  if (changed) await chrome.storage.session.set({ [SAVE_TABS_KEY]: map }).catch(() => {});
});

chrome.tabs.onRemoved.addListener(async tabId => {
  const s = await getState();
  if (tabId === s.tabId) stopSession();
});

chrome.tabs.onUpdated.addListener(async (tabId, changeInfo) => {
  if (changeInfo.status !== 'complete') return;
  const s = await getState();
  if (tabId !== s.tabId) return;
  if (s.pending) { continueInTab(tabId, s.pending); return; }
  if (!s.session) return;
  // Safety net: the page we were reading is gone but we never heard about it.
  const session = s.session;
  const pong = await toTab(tabId, { type: 'kr-ping' });
  if (pong && pong.session === session) return;
  // The page's own "leaving" message may have been handled while we waited.
  const now = await getState();
  if (now.tabId !== tabId) return;
  if (!now.pending) {
    if (now.session !== session) return; // a new session started meanwhile
    await pageLeft(false, session);
  }
  const after = await getState();
  if (after.pending) continueInTab(tabId, after.pending);
});

chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
  if (!msg || msg.target === 'offscreen') return false;
  handleMessage(msg, sender).then(
    r => sendResponse(r === undefined ? { ok: true } : r),
    e => sendResponse({ ok: false, error: e && e.message ? e.message : String(e) })
  );
  return true;
});

async function handleMessage(msg, sender) {
  const s = await getState();
  const tabId = sender.tab ? sender.tab.id : null;

  // Events from the audio player -> forward to the reading tab.
  if (msg.target === 'sw' && msg.type === 'kr-event') {
    if (!msg.session || msg.session !== s.session) return;
    if (msg.event && msg.event.type === 'stop-request') { await stopSession({ notifyTab: true }); return; }
    toTab(s.tabId, { type: 'kr-event', session: msg.session, event: msg.event });
    return;
  }

  switch (msg.type) {
    case 'kr-start': {
      if (tabId == null) return { ok: false, error: 'No tab' };
      const settings = await getSettings();
      const problem = await checkSetup(settings);
      if (problem) return { ok: false, setup: true, error: problem };
      if (s.tabId != null && s.tabId !== tabId) toTab(s.tabId, { type: 'kr-stopped' });
      await saveState({ tabId, session: msg.session, pending: null });
      const startMsg = {
        type: 'start',
        session: msg.session,
        chunks: msg.chunks,
        startIndex: msg.startIndex || 0,
        paused: !!msg.paused,
        title: sender.tab.title || '',
        base: krApiBase(settings.serverUrl),
        voice: settings.voice,
        speed: settings.speed
      };
      let r = null;
      for (let attempt = 0; attempt < 2 && !(r && r.ok); attempt++) {
        await ensureOffscreen();
        r = await toOffscreen(startMsg);
      }
      if (!r || !r.ok) return { ok: false, error: 'Couldn’t start the audio player. Try again.' };
      return { ok: true, speed: krClampSpeed(settings.speed) };
    }

    case 'kr-control': {
      if (msg.action === 'stop') {
        if (msg.session && msg.session === s.session) await stopSession();
        return { ok: true };
      }
      // ok:false tells the page to restart playback from its own copy of the text.
      if (tabId !== s.tabId || msg.session !== s.session) return { ok: false };
      const r = await toOffscreen({ type: msg.action, index: msg.index, session: msg.session });
      return r || { ok: false };
    }

    case 'kr-page-leaving':
      if (tabId != null && tabId === s.tabId && msg.session && msg.session === s.session) {
        await pageLeft(msg.paused, msg.session);
      }
      return;

    case 'kr-speed':
      await chrome.storage.sync.set({ speed: krClampSpeed(msg.speed) });
      return;

    case 'kr-get-settings': {
      const settings = await getSettings();
      return { speed: krClampSpeed(settings.speed), autoContinue: !!settings.autoContinue };
    }

    case 'kr-open-options':
      chrome.runtime.openOptionsPage();
      return;

    case 'kn-boot':
      // This page already has notes: load the notes script so the highlights come back.
      if (tabId != null) await ensureNotes(tabId);
      return;

    case 'kn-open-manager':
      await openNotesManager(msg.focus);
      return;

    case 'kn-read': {
      // Notes sidebar -> read these notes aloud with the Kokoro reader in the same tab.
      if (tabId == null || !Array.isArray(msg.chunks) || !msg.chunks.length) return { ok: false, error: 'Nothing to read.' };
      const settings = await getSettings();
      const problem = await checkSetup(settings);
      if (problem) { chrome.runtime.openOptionsPage(); return { ok: false, error: problem }; }
      if (!(await ensureContent(tabId))) return { ok: false, error: 'The reader can’t run on this page.' };
      await toTab(tabId, { type: 'kr-read-text', chunks: msg.chunks.map(c => String(c).slice(0, 4000)).slice(0, 500) });
      return { ok: true };
    }

    case 'ko-region': await onRegion(msg, sender); return;
    case 'ko-shot-evidence': {
      try { return { ok: true, ...(await shotForEvidence(Number(msg.tabId), msg.returnTabId != null ? Number(msg.returnTabId) : null)) }; }
      catch (e) { return { ok: false, error: e && e.message ? e.message : String(e) }; }
    }
    case 'ko-get-headers': {
      const all = (await chrome.storage.session.get(HEADERS_KEY))[HEADERS_KEY] || {};
      return { ok: true, record: all[msg.tabId] || null };
    }
    case 'kr-open-save':
      if (sender.tab) await openSave(sender.tab, { view: ['video', 'image', 'audio'].includes(msg.view) ? msg.view : 'document' });
      return;
  }
}

