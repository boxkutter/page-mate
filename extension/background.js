chrome.commands.onCommand.addListener(async (command, tab) => {
  if (command === 'toggle-notes' || command === 'highlight-selection') {
    if (!tab) [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (tab) notesCommand(tab, command === 'toggle-notes' ? { type: 'kn-toggle' } : { type: 'kn-highlight', color: 'yellow' });
    return;
  }
  if (command === 'save-page' || command === 'save-video') {
    if (!tab) [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    if (tab) openSave(tab, { view: command === 'save-video' ? 'video' : 'document' });
    return;
  }
  if (command !== 'toggle-pause') return;
  const s = await getState();
  if (s.tabId != null) toTab(s.tabId, { type: 'kr-toggle-pause' });
});

// ---------- Notes ----------

async function ensureNotes(tabId) {
  const pong = await toTab(tabId, { type: 'kn-ping' });
  if (pong && pong.alive) return true;
  try {
    await chrome.scripting.insertCSS({ target: { tabId }, files: ['notes.css'] });
    await chrome.scripting.executeScript({ target: { tabId }, files: ['notes-core.js', 'notes-dom.js', 'notes.js'] });
    return true;
  } catch (e) {
    console.warn('PageMate notes cannot run on this page:', e.message);
    return false;
  }
}

async function notesCommand(tab, msg) {
  if (!tab || tab.id == null) return;
  if (!(await ensureNotes(tab.id))) {
    flashBadge(tab.id, '!', 'Notes can’t run on this page (browser-internal or protected page)');
    return;
  }
  clearBadge(tab.id);
  // The script has just been injected: give it a moment to finish loading its notes.
  for (let i = 0; i < 10; i++) {
    const r = await toTab(tab.id, msg);
    if (r) return;
    await new Promise(res => setTimeout(res, 120));
  }
}

async function openNotesManager(focusKey) {
  const url = chrome.runtime.getURL('notes.html') + (focusKey ? '#focus=' + encodeURIComponent(focusKey) : '');
  const stored = await chrome.storage.session.get('krNotesTab').catch(() => ({}));
  const id = stored.krNotesTab;
  if (id != null) {
    try {
      const t = await chrome.tabs.get(id);
      await chrome.tabs.update(t.id, { active: true, url });
      if (t.windowId != null) chrome.windows.update(t.windowId, { focused: true }).catch(() => {});
      return;
    } catch (_) {}
  }
  const t = await chrome.tabs.create({ url });
  await chrome.storage.session.set({ krNotesTab: t.id }).catch(() => {});
}

// Once access to sites is allowed, pages that already have notes get their highlights back
// automatically. The registered script only looks up "do I have notes for this page?".
async function syncNotesBoot() {
  try {
    const has = await chrome.permissions.contains({ origins: KR_ALL_SITES });
    const { notesAuto } = await chrome.storage.sync.get({ notesAuto: true });
    const registered = await chrome.scripting.getRegisteredContentScripts({ ids: ['kn-boot'] });
    if (has && notesAuto) {
      if (!registered.length) {
        await chrome.scripting.registerContentScripts([{ id: 'kn-boot', matches: KR_ALL_SITES, js: ['notes-core.js', 'notes-boot.js'], runAt: 'document_idle', persistAcrossSessions: true }]);
      }
    } else if (registered.length) {
      await chrome.scripting.unregisterContentScripts({ ids: ['kn-boot'] });
    }
  } catch (e) {
    console.warn('PageMate notes boot:', e.message);
  }
}
syncNotesBoot();
chrome.permissions.onAdded.addListener(syncNotesBoot);
chrome.permissions.onRemoved.addListener(syncNotesBoot);
chrome.storage.onChanged.addListener((changes, area) => { if (area === 'sync' && changes.notesAuto) syncNotesBoot(); });

// ---------- the Save page ----------

// Which Save tab belongs to which page. (We can't search tabs by URL: without the
// "tabs" permission the browser hides every tab's address, even our own pages'.)
const SAVE_TABS_KEY = 'krSaveTabs';

async function openSave(tab, { view = 'document', scope, frameId, srcUrl } = {}) {
  if (!tab || tab.id == null) return;
  const q = new URLSearchParams({ tab: String(tab.id), view });
  if (scope) q.set('scope', scope);
  if (frameId != null && frameId > 0) q.set('frame', String(frameId));
  if (srcUrl) q.set('src', srcUrl);
  const url = chrome.runtime.getURL('save.html?' + q);

  const stored = await chrome.storage.session.get(SAVE_TABS_KEY).catch(() => ({}));
  const map = stored[SAVE_TABS_KEY] || {};
  // Reuse the Save tab already open for this page, if any.
  if (map[tab.id] != null) {
    try {
      const existing = await chrome.tabs.get(map[tab.id]);
      await chrome.tabs.update(existing.id, { url, active: true });
      if (existing.windowId != null) chrome.windows.update(existing.windowId, { focused: true }).catch(() => {});
      return;
    } catch (_) { delete map[tab.id]; } // it was closed
  }
  const created = await chrome.tabs.create({ url, index: tab.index + 1, openerTabId: tab.id, active: true });
  map[tab.id] = created.id;
  await chrome.storage.session.set({ [SAVE_TABS_KEY]: map }).catch(() => {});
}

chrome.tabs.onRemoved.addListener(async tabId => {
  const nt = await chrome.storage.session.get('krNotesTab').catch(() => ({}));
  if (nt.krNotesTab === tabId) chrome.storage.session.remove('krNotesTab').catch(() => {});
  const stored = await chrome.storage.session.get(SAVE_TABS_KEY).catch(() => ({}));
  const map = stored[SAVE_TABS_KEY];
  if (!map) return;
  let changed = false;
  for (const [src, save] of Object.entries(map)) {
    if (Number(src) === tabId || save === tabId) { delete map[src]; changed = true; }
  }
  if (changed) await chrome.storage.session.set({ [SAVE_TABS_KEY]: map }).catch(() => {});
});

chrome.tabs.onRemoved.addListener(async tabId => {
  const s = await getState();
  if (tabId === s.tabId) stopSession();
});

chrome.tabs.onUpdated.addListener(async (tabId, changeInfo) => {
  if (changeInfo.status !== 'complete') return;
  const s = await getState();
  if (tabId !== s.tabId) return;
  if (s.pending) { continueInTab(tabId, s.pending); return; }
  if (!s.session) return;
  // Safety net: the page we were reading is gone but we never heard about it.
  const session = s.session;
  const pong = await toTab(tabId, { type: 'kr-ping' });
  if (pong && pong.session === session) return;
  // The page's own "leaving" message may have been handled while we waited.
  const now = await getState();
  if (now.tabId !== tabId) return;
  if (!now.pending) {
    if (now.session !== session) return; // a new session started meanwhile
    await pageLeft(false, session);
  }
  const after = await getState();
  if (after.pending) continueInTab(tabId, after.pending);
});

chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
  if (!msg || msg.target === 'offscreen') return false;
  handleMessage(msg, sender).then(
    r => sendResponse(r === undefined ? { ok: true } : r),
    e => sendResponse({ ok: false, error: e && e.message ? e.message : String(e) })
  );
  return true;
});

async function handleMessage(msg, sender) {
  const s = await getState();
  const tabId = sender.tab ? sender.tab.id : null;

  // Events from the audio player -> forward to the reading tab.
  if (msg.target === 'sw' && msg.type === 'kr-event') {
    if (!msg.session || msg.session !== s.session) return;
    if (msg.event && msg.event.type === 'stop-request') { await stopSession({ notifyTab: true }); return; }
    toTab(s.tabId, { type: 'kr-event', session: msg.session, event: msg.event });
    return;
  }

  switch (msg.type) {
    case 'kr-start': {
      if (tabId == null) return { ok: false, error: 'No tab' };
      const settings = await getSettings();
      const problem = await checkSetup(settings);
      if (problem) return { ok: false, setup: true, error: problem };
      if (s.tabId != null && s.tabId !== tabId) toTab(s.tabId, { type: 'kr-stopped' });
      await saveState({ tabId, session: msg.session, pending: null });
      const startMsg = {
        type: 'start',
        session: msg.session,
        chunks: msg.chunks,
        startIndex: msg.startIndex || 0,
        paused: !!msg.paused,
        title: sender.tab.title || '',
        base: krApiBase(settings.serverUrl),
        voice: settings.voice,
        speed: settings.speed
      };
      let r = null;
      for (let attempt = 0; attempt < 2 && !(r && r.ok); attempt++) {
        await ensureOffscreen();
        r = await toOffscreen(startMsg);
      }
      if (!r || !r.ok) return { ok: false, error: 'Couldn’t start the audio player. Try again.' };
      return { ok: true, speed: krClampSpeed(settings.speed) };
    }

    case 'kr-control': {
      if (msg.action === 'stop') {
        if (msg.session && msg.session === s.session) await stopSession();
        return { ok: true };
      }
      // ok:false tells the page to restart playback from its own copy of the text.
      if (tabId !== s.tabId || msg.session !== s.session) return { ok: false };
      const r = await toOffscreen({ type: msg.action, index: msg.index, session: msg.session });
      return r || { ok: false };
    }

    case 'kr-page-leaving':
      if (tabId != null && tabId === s.tabId && msg.session && msg.session === s.session) {
        await pageLeft(msg.paused, msg.session);
      }
      return;

    case 'kr-speed':
      await chrome.storage.sync.set({ speed: krClampSpeed(msg.speed) });
      return;

    case 'kr-get-settings': {
      const settings = await getSettings();
      return { speed: krClampSpeed(settings.speed), autoContinue: !!settings.autoContinue };
    }

    case 'kr-open-options':
      chrome.runtime.openOptionsPage();
      return;

    case 'kn-boot':
      // This page already has notes: load the notes script so the highlights come back.
      if (tabId != null) await ensureNotes(tabId);
      return;

    case 'kn-open-manager':
      await openNotesManager(msg.focus);
      return;

    case 'kn-read': {
      // Notes sidebar -> read these notes aloud with the Kokoro reader in the same tab.
      if (tabId == null || !Array.isArray(msg.chunks) || !msg.chunks.length) return { ok: false, error: 'Nothing to read.' };
      const settings = await getSettings();
      const problem = await checkSetup(settings);
      if (problem) { chrome.runtime.openOptionsPage(); return { ok: false, error: problem }; }
      if (!(await ensureContent(tabId))) return { ok: false, error: 'The reader can’t run on this page.' };
      await toTab(tabId, { type: 'kr-read-text', chunks: msg.chunks.map(c => String(c).slice(0, 4000)).slice(0, 500) });
      return { ok: true };
    }

    case 'kr-open-save':
      if (sender.tab) await openSave(sender.tab, { view: ['video', 'image', 'audio'].includes(msg.view) ? msg.view : 'document' });
      return;
  }
}

// Settings changed (options page or player) -> apply to the current reading.
chrome.storage.onChanged.addListener(async (changes, area) => {
  if (area !== 'sync') return;
  const s = await getState();
  if (!s.session) return;
  if (changes.voice) toOffscreen({ type: 'voice', voice: changes.voice.newValue });
  if (changes.speed) toOffscreen({ type: 'speed', speed: changes.speed.newValue });
  if (changes.serverUrl) stopSession({ notifyTab: true });
});


// ---------- video detection ----------
// While the user has allowed access to sites, note the addresses of video files
// and streams (.mp4, .m3u8, .mpd ...) each tab loads, so the Save page can offer
// them even when the player hides them behind a blob: URL. Only the address, type
// and size are kept, in memory for this browser session; nothing is sent anywhere.

const MEDIA_KEY = 'krMedia';
const MAX_PER_TAB = 60;
const MIN_FILE_BYTES = 150 * 1024;           // ignore tiny clips (ads, previews, UI sounds)
const SEGMENT_URL = /\.(ts|m4s|cmfv|cmfa|fmp4|vtt|webvtt|aac|mp2t)(?:[?#]|$)/i;
const MEDIA_URL = /\.(m3u8|mpd|mp4|m4v|webm|mov|mkv|m4a|mp3|ogv|ogg|opus|flac|wav)(?:[?#]|$)/i;

let sniffEnabled = true;
chrome.storage.sync.get({ sniffVideos: true }).then(r => { sniffEnabled = r.sniffVideos !== false; }).catch(() => {});
chrome.storage.onChanged.addListener((changes, area) => {
  if (area === 'sync' && changes.sniffVideos) sniffEnabled = changes.sniffVideos.newValue !== false;
});

let mediaQueue = Promise.resolve();
function updateMedia(fn) {
  mediaQueue = mediaQueue.then(async () => {
    const r = await chrome.storage.session.get(MEDIA_KEY);
    const all = r[MEDIA_KEY] || {};
    if (fn(all) !== false) await chrome.storage.session.set({ [MEDIA_KEY]: all });
  }).catch(() => {});
  return mediaQueue;
}

function headerValue(headers, name) {
  const h = (headers || []).find(x => x.name.toLowerCase() === name);
  return h ? h.value || '' : '';
}

function classifyMedia(details) {
  const url = details.url;
  if (SEGMENT_URL.test(url)) return null;
  const mime = headerValue(details.responseHeaders, 'content-type').split(';')[0].trim().toLowerCase();
  if (/^video\/(mp2t|iso\.segment)$/.test(mime) || mime === 'audio/aac' || mime === 'text/vtt') return null;
  let kind = null;
  if (/mpegurl/.test(mime) || /\.m3u8(?:[?#]|$)/i.test(url)) kind = 'hls';
  else if (/dash\+xml/.test(mime) || /\.mpd(?:[?#]|$)/i.test(url)) kind = 'dash';
  else if (/^(video|audio)\//.test(mime) || (mime === 'application/octet-stream' && MEDIA_URL.test(url))) kind = 'file';
  else if (MEDIA_URL.test(url) && details.type === 'media') kind = 'file';
  if (!kind) return null;

  let size = parseInt(headerValue(details.responseHeaders, 'content-length'), 10) || 0;
  const range = /\/(\d+)\s*$/.exec(headerValue(details.responseHeaders, 'content-range'));
  if (range) size = parseInt(range[1], 10) || size;
  if (kind === 'file' && size && size < MIN_FILE_BYTES) return null;
  return { url, kind, mime, size };
}

chrome.webRequest.onResponseStarted.addListener(details => {
  if (!sniffEnabled || details.tabId < 0 || details.statusCode >= 400) return;
  const found = classifyMedia(details);
  if (!found) return;
  const entry = {
    ...found,
    frameId: details.frameId,
    referer: details.documentUrl || details.initiator || '',
    at: Date.now()
  };
  updateMedia(all => {
    const list = all[details.tabId] || [];
    const key = entry.url.split('#')[0];
    const existing = list.find(e => e.url.split('#')[0] === key);
    if (existing) {
      // Progressive downloads arrive as many ranged requests: keep the best size info.
      if (entry.size > (existing.size || 0)) { existing.size = entry.size; return true; }
      return false;
    }
    list.push(entry);
    all[details.tabId] = list.slice(-MAX_PER_TAB);
  });
}, { urls: ['http://*/*', 'https://*/*'], types: ['media', 'xmlhttprequest', 'other'] }, ['responseHeaders']);

// A new page in the tab: its list starts over.
chrome.webRequest.onBeforeRequest.addListener(details => {
  if (details.tabId < 0) return;
  updateMedia(all => { if (!all[details.tabId]) return false; delete all[details.tabId]; });
}, { urls: ['http://*/*', 'https://*/*'], types: ['main_frame'] });

chrome.tabs.onRemoved.addListener(tabId => {
  updateMedia(all => { if (!all[tabId]) return false; delete all[tabId]; });
});
