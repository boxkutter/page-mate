importScripts('common.js');

// ---------- persistent state ----------
// MV3 service workers are shut down after ~30s idle, so anything we need
// later (which tab is reading, which session) lives in storage.session.

const STATE_KEY = 'krState';
const EMPTY_STATE = { tabId: null, session: null, pending: null };
const CONTINUE_WINDOW_MS = 2 * 60 * 1000;

let state = { ...EMPTY_STATE };
const stateReady = chrome.storage.session.get(STATE_KEY)
  .then(r => { if (r && r[STATE_KEY]) state = { ...EMPTY_STATE, ...r[STATE_KEY] }; })
  .catch(() => {});

async function getState() {
  await stateReady;
  return state;
}

async function saveState(patch) {
  await stateReady;
  state = { ...state, ...patch };
  try { await chrome.storage.session.set({ [STATE_KEY]: state }); } catch (_) {}
}

async function getSettings() {
  return chrome.storage.sync.get(KR_DEFAULTS);
}

// ---------- offscreen audio document ----------

let offscreenQueue = Promise.resolve();
function queueOffscreen(fn) {
  const p = offscreenQueue.then(fn);
  offscreenQueue = p.catch(() => {});
  return p;
}

async function hasOffscreen() {
  const contexts = await chrome.runtime.getContexts({ contextTypes: ['OFFSCREEN_DOCUMENT'] });
  return contexts.length > 0;
}

function ensureOffscreen() {
  return queueOffscreen(async () => {
    if (await hasOffscreen()) return;
    await chrome.offscreen.createDocument({
      url: 'offscreen.html',
      // BLOBS: audio is held as blob URLs. Listing it also keeps the browser
      // from closing the document 30s into a pause.
      reasons: ['AUDIO_PLAYBACK', 'BLOBS'],
      justification: 'Plays speech generated by the user\'s Kokoro server'
    });
  });
}

// Closes the audio document, unless a new reading session started meanwhile.
function closeOffscreen() {
  return queueOffscreen(async () => {
    if ((await getState()).session) return;
    if (await hasOffscreen()) await chrome.offscreen.closeDocument();
  }).catch(() => {});
}

async function toOffscreen(msg) {
  try {
    if (!(await hasOffscreen())) return null;
    return (await chrome.runtime.sendMessage({ target: 'offscreen', ...msg })) || null;
  } catch (_) {
    return null;
  }
}

// ---------- tabs ----------

function toTab(tabId, msg) {
  if (tabId == null) return Promise.resolve(null);
  return chrome.tabs.sendMessage(tabId, msg, { frameId: 0 }).catch(() => null);
}

async function ensureContent(tabId) {
  const pong = await toTab(tabId, { type: 'kr-ping' });
  if (pong && pong.alive) return true;
  try {
    await chrome.scripting.insertCSS({ target: { tabId }, files: ['highlight.css'] });
    await chrome.scripting.executeScript({ target: { tabId }, files: ['content.js'] });
    return true;
  } catch (e) {
    console.warn('PageMate cannot run on this page:', e.message);
    return false;
  }
}

function flashBadge(tabId, text, title) {
  chrome.action.setBadgeBackgroundColor({ tabId, color: '#b33b2e' }).catch(() => {});
  chrome.action.setBadgeText({ tabId, text }).catch(() => {});
  if (title) chrome.action.setTitle({ tabId, title }).catch(() => {});
}

function clearBadge(tabId) {
  chrome.action.setBadgeText({ tabId, text: '' }).catch(() => {});
  chrome.action.setTitle({ tabId, title: 'Read this page aloud (Alt+Shift+R)' }).catch(() => {});
}

// Returns an error string if the extension isn't ready to talk to the server.
async function checkSetup(settings) {
  let pattern;
  try { pattern = krOriginPattern(settings.serverUrl); } catch (_) {
    return 'Set your Kokoro server address in the settings.';
  }
  const allowed = await chrome.permissions.contains({ origins: [pattern] }).catch(() => false);
  if (!allowed) return 'The extension needs permission to reach your Kokoro server. Click Connect in the settings.';
  return null;
}

async function activate(tab, opts = {}) {
  if (!tab || tab.id == null) return;
  const settings = await getSettings();
  if (await checkSetup(settings)) { chrome.runtime.openOptionsPage(); return; }
  if (!(await ensureContent(tab.id))) {
    flashBadge(tab.id, '!', 'PageMate can’t read this page (browser-internal or protected page)');
    return;
  }
  clearBadge(tab.id);
  await toTab(tab.id, {
    type: 'kr-toggle',
    mode: opts.mode || 'toggle',
    selectionText: opts.selectionText || ''
  });
}

async function stopSession({ notifyTab = false } = {}) {
  const s = await getState();
  const tabId = s.tabId;
  await saveState({ ...EMPTY_STATE });
  await toOffscreen({ type: 'stop' });
  closeOffscreen();
  if (notifyTab) toTab(tabId, { type: 'kr-stopped' });
}

// The reading page went away (navigation / reload). Stop its audio and,
// if enabled, pick up reading on whatever loads next in that tab.
async function pageLeft(paused, session) {
  // Record this first: the tab may finish loading the next page while we're
  // still awaiting below. A pause reported by the page always wins.
  const s = await getState();
  const wasPaused = !!paused || !!(s.pending && s.pending.paused);
  await saveState({ session: null, pending: { paused: wasPaused, at: Date.now() } });
  await toOffscreen({ type: 'stop', session });
  const settings = await getSettings();
  if (!settings.autoContinue) {
    await saveState({ ...EMPTY_STATE });
    closeOffscreen();
  }
}

async function continueInTab(tabId, pending) {
  await saveState({ pending: null });
  if (Date.now() - pending.at > CONTINUE_WINDOW_MS) { await stopSession(); return; }
  const settings = await getSettings();
  if (!settings.autoContinue || await checkSetup(settings) || !(await ensureContent(tabId))) {
    await stopSession();
    return;
  }
  const r = await toTab(tabId, { type: 'kr-autostart', paused: !!pending.paused });
  if (!r) await stopSession();
}

